const message = (prompt = 'queued') => ({ id: randomUUID(), runId: 'run', prompt, attachments: [], status: 'queued', createdAt: new Date().toISOString() });
const initial = () => ({ type: 'user', uuid: randomUUID(), message: { role: 'user', content: 'first' }, parent_tool_use_id: null });
test('one input is in flight, queued messages can be removed, and closing cancels only unsent inputs', async () => {
    const changes = [], q = createInputQueue(initial(), x => changes.push(x));
    await q.prompt.next();
    const a = message('second'), b = message('third');
    q.enqueue(a, []);
    q.enqueue(b, []);
    assert.equal(q.cancel(b.id), true);
    assert.equal(q.result(), false);
    const second = await q.prompt.next();
    assert.equal(second.value.message.content, 'second');
    assert.equal(changes.at(-1).status, 'sent');
    q.close();
    assert.equal(changes.at(-1).status, 'unknown');
    assert.equal((await q.prompt.next()).done, true);
    assert.throws(() => q.enqueue(message(), []), { code: 'run-ended' });
});
test('background activity keeps the input alive; queued messages during idle are sent and no input races final completion', async () => {
    const changes = [], q = createInputQueue(initial(), x => changes.push(x));
    await q.prompt.next();
    assert.equal(q.result(true), false);
    assert.equal(q.idle, true);
    const a = message();
    q.enqueue(a, []);
    assert.equal((await q.prompt.next()).value.uuid, a.id);
    assert.equal(q.result(), true);
    assert.equal(changes.at(-1).status, 'completed');
    assert.throws(() => q.enqueue(message(), []), { code: 'run-ended' });
    q.close();
});
test('chunk uploads are idempotent and bounded; bytes stay private while metadata survives restart', async (t) => {
    const dir = await mkdtemp(join(tmpdir(), 'claude-interactive-assets-'));
    let f = await createRunsFixture(join(dir, 'index.sqlite'));
    t.after(async () => { await f.close(); await rm(dir, { recursive: true, force: true }); });
    const bytes = Buffer.from('hello 世界\n'.repeat(30000)), header = { name: 'notes.txt', mime: 'text/plain', size: bytes.length, idempotencyKey: 'upload-1' };
    let upload = await f.runs.beginAttachment(header);
    assert.equal(upload.id, (await f.runs.beginAttachment(header)).id);
    const first = { offset: 0, data: bytes.subarray(0, 192 * 1024).toString('base64') };
    upload = await f.runs.appendAttachment(upload.id, first);
    assert.deepEqual(await f.runs.appendAttachment(upload.id, first), upload);
    await assert.rejects(f.runs.appendAttachment(upload.id, { offset: 1, data: 'YWJj' }), { code: 'attachment-offset' });
    while (!upload.ready) {
        const offset = upload.received;
        upload = await f.runs.appendAttachment(upload.id, { offset, data: bytes.subarray(offset, offset + 192 * 1024).toString('base64') });
    }
    assert.ok(upload.ready);
    const data = await f.store.readAttachments([upload.id]);
    assert.deepEqual(Buffer.from(data[0].data, 'base64'), bytes);
    const thread = await f.runs.createThread({ projectPath: '/p' }), run = await f.runs.startRun(thread.id, { prompt: 'read attachment', attachmentIds: [upload.id], idempotencyKey: 'start' });
    assert.equal(run.attachments[0].name, 'notes.txt');
    assert.equal('data' in run.attachments[0], false);
    assert.ok(content('read', data)[1].text.includes('世界'));
    await assert.rejects(f.runs.discardAttachment(upload.id), { code: 'attachment-in-use' });
    f.sdk.runs[0].finish({ kind: 'result', result: sampleResult() });
    f.sdk.runs[0].exit();
    await f.runs.waitRun(run.id);
    await f.close();
    f = await createRunsFixture(join(dir, 'index.sqlite'));
    assert.equal((await f.runs.getRun(run.id)).attachments[0].sha256, data[0].sha256);
    await assert.rejects(f.runs.beginAttachment({ ...header, mime: 'image/png', idempotencyKey: 'bad-type', size: 4 }).then(v => f.runs.appendAttachment(v.id, { offset: 0, data: 'dGVzdA==' })), { code: 'attachment-invalid' });
});
test('queued submissions use durable request identities; cancellation and restart never replay uncertain inputs', async (t) => {
    const dir = await mkdtemp(join(tmpdir(), 'claude-interactive-ledger-')), sdk = fakeSdk();
    let f = await createRunsFixture(join(dir, 'index.sqlite'), { sdk });
    t.after(async () => { await f.close(); await rm(dir, { recursive: true, force: true }); });
    const thread = await f.runs.createThread({ projectPath: '/p' }), run = await f.runs.startRun(thread.id, { prompt: 'first', idempotencyKey: 'first' }), sent = [];
    sdk.runs[0].handle.enqueue = (view, assets) => { sent.push(view); sdk.runs[0].hooks.onEvent({ type: 'input', message: view }); };
    sdk.runs[0].handle.cancelInput = id => { sdk.runs[0].hooks.onEvent({ type: 'input', message: { ...sent.find(v => v.id === id), status: 'cancelled' } }); return true; };
    const a = await f.runs.appendMessage(run.id, { prompt: 'second', idempotencyKey: 'q1' });
    assert.equal((await f.runs.appendMessage(run.id, { prompt: 'second', idempotencyKey: 'q1' })).id, a.id);
    assert.equal(sent.length, 1);
    await assert.rejects(f.runs.appendMessage(run.id, { prompt: 'changed', idempotencyKey: 'q1' }), { code: 'idempotency-conflict' });
    await f.runs.cancelMessage(run.id, a.id);
    await waitFor(() => f.runs.getRunView(run.id).inputs.at(-1).status === 'cancelled');
    const b = await f.runs.appendMessage(run.id, { prompt: 'third', idempotencyKey: 'q2' });
    sdk.runs[0].finish({ kind: 'result', result: sampleResult() });
    sdk.runs[0].exit();
    await f.runs.waitRun(run.id);
    await f.close();
    f = await createRunsFixture(join(dir, 'index.sqlite'));
    assert.equal((await f.runs.listMessages(run.id)).find(v => v.id === b.id).status, 'unknown');
    assert.equal((await f.runs.listMessages(run.id)).find(v => v.id === a.id).status, 'cancelled');
    assert.equal(f.sdk.runs.length, 0);
});
test('child deltas finalize without duplicate text; child tool results, auth, background levels and progress remain separate', () => {
    const translate = createMessageTranslator();
    let view = emptyRunView('r', 't');
    const fold = m => { for (const e of translate(m))
        view = applyRunEvent(view, e); };
    const frame = event => ({ type: 'stream_event', parent_tool_use_id: 'parent', event });
    fold(frame({ type: 'message_start', message: { id: 'child' } }));
    fold(frame({ type: 'content_block_start', index: 0, content_block: { type: 'text' } }));
    fold(frame({ type: 'content_block_delta', index: 0, delta: { type: 'text_delta', text: 'live' } }));
    assert.equal(view.agentMessages[0].message.blocks[0].text, 'live');
    fold({ type: 'assistant', parent_tool_use_id: 'parent', message: { id: 'child', content: [{ type: 'text', text: 'final' }] } });
    assert.equal(view.agentMessages.length, 1);
    assert.equal(view.agentMessages[0].message.blocks[0].text, 'final');
    fold({ type: 'user', uuid: 'result', parent_tool_use_id: 'parent', message: { content: [{ type: 'tool_result', tool_use_id: 'tool', content: 'ok' }] } });
    assert.equal(view.agentMessages.at(-1).message.blocks[0].kind, 'tool_result');
    assert.equal(view.items.length, 0);
    fold({ type: 'auth_status', isAuthenticating: true, output: ['SECRET'], error: undefined });
    assert.deepEqual(view.auth, { authenticating: true, failed: false });
    assert.doesNotMatch(JSON.stringify(view), /SECRET/);
    fold({ type: 'system', subtype: 'background_tasks_changed', tasks: [{ task_id: 'a' }, { task_id: 'watch', ambient: true }] });
    assert.deepEqual(view.backgroundTaskIds, ['a']);
    fold({ type: 'system', subtype: 'background_tasks_changed', tasks: [] });
    assert.deepEqual(view.backgroundTaskIds, []);
});
