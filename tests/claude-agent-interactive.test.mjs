test('a failed queued turn is terminal and never releases another queued message', async () => {
    const states = [], q = createInputQueue(initial(), x => states.push(x));
    await q.prompt.next();
    const a = message('fail'), b = message('not-sent');
    q.enqueue(a, []);
    q.enqueue(b, []);
    q.result();
    await q.prompt.next();
    assert.equal(q.result(false, true), true);
    q.close();
    assert.equal(states.findLast(x => x.id === a.id).status, 'failed');
    assert.equal(states.findLast(x => x.id === b.id).status, 'cancelled');
    assert.equal((await q.prompt.next()).done, true);
});

