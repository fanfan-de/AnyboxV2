import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const snapshot = new URL('./assets/provider-logos.json', import.meta.url)
const upstreamLicense = new URL('../packages/models/assets/models.dev.LICENSE', import.meta.url)

/** Copy the reviewed, drawing-only Models.dev SVG snapshot into each app's web resources. */
export async function buildProviderLogos(vendorDirectory, appId) {
  const [data, license] = await Promise.all([
    readFile(snapshot, 'utf8'),
    readFile(upstreamLicense, 'utf8'),
  ])
  const { source, logos } = JSON.parse(data)
  // Both products can be mounted in the same document, so their SVG IDs must stay distinct.
  const appLogos = Object.fromEntries(Object.entries(logos).map(([id, svg]) => [
    id, svg.replace(/(id="|url\(#)provider-logo-/g, `$1${appId}--provider-logo-`),
  ]))
  const attribution = `Models.dev Provider logos from ${source.repository}/tree/${source.commit}\nSource files: ${source.path}`
  const module = `// Generated by scripts/build-provider-logos.mjs.
/*
${attribution}

${license.trimEnd()}
*/
const logos = ${JSON.stringify(appLogos, null, 2)}

export function providerLogo(id) {
  return Object.hasOwn(logos, id) ? logos[id] : undefined
}
`
  await mkdir(vendorDirectory, { recursive: true })
  await Promise.all([
    writeFile(join(vendorDirectory, 'provider-logos.js'), module),
    writeFile(join(vendorDirectory, 'provider-logos.LICENSE.txt'), `${attribution}\n\n${license}`),
  ])
}
